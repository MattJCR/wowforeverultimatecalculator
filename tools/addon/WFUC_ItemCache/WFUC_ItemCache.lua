  say(label .. ': objetos ' .. math.min(db.idx - 1, #ids) .. ' / ' .. #ids .. ', hechizos ' .. math.min(db.sidx - 1, #spells) .. ' / ' .. #spells .. '; ya conocidos por el cliente de los pedidos: ' .. known())
end

local function reset()
