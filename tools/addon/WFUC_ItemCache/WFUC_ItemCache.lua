  ticker = C_Timer.NewTicker(INTERVAL, tick)
  say('retomando: objetos ' .. math.min(db.idx, #ids + 1) - 1 .. ' / ' .. #ids .. ', hechizos ' .. math.min(db.sidx, #spells + 1) - 1 .. ' / ' .. #spells .. ' (se detiene en combate o al cambiar de zona)')
  refresh()
end

local function status()
